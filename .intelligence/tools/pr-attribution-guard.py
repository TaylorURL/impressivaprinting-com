#!/usr/bin/env python3
"""Strips AI attribution out of pull request bodies on the owner's repos.

The global INTELLIGENCE.md forbids AI attribution anywhere on GitHub, and the model
honours that in the text it writes. What it cannot honour is text it does not
write: some harnesses append a "Generated by Claude Code" footer to a pull
request body server-side, after the create call returns. A cloud run therefore
publishes the footer while doing everything right, and nobody sees it until
someone opens the pull request.

So the rule needs a sweep behind it rather than another line telling the model
to be careful. Editing a body through the API does not re-trigger the append,
which is what makes repair reliable: strip the footer once and it stays gone.
"""

import argparse
import importlib.util
import json
import re
import subprocess
import sys
from pathlib import Path


def _shared():
    """The shared _lib module, loaded by path.

    This tool runs as a script from arbitrary directories, so the module is
    found beside this file rather than through sys.path, with the installed
    tree as the fallback for a copy executed from elsewhere.
    """
    here = Path(__file__).resolve().parent / "_lib.py"
    path = here if here.is_file() else Path.home() / ".intelligence" / "tools" / "_lib.py"
    spec = importlib.util.spec_from_file_location("intelligence_tools_lib", path)
    module = importlib.util.module_from_spec(spec)
    spec.loader.exec_module(module)
    return module


# Reading the wrong state root is silent: the sweep finds no repos and reports
# nothing to do, which is indistinguishable from a clean result. So the root is
# _lib's, the same one the pass tooling writes.
_state_root = _shared().state_root

STATE = _state_root()

# Each pattern matches a whole attribution artifact, not a bare mention, so a
# pull request that legitimately discusses Claude keeps its prose.
PATTERNS = [
    # Trailing footer, with or without the horizontal rule above it.
    re.compile(
        r"\n*(?:^|\n)-{3,}\s*\n+_?Generated (?:by|with) \[Claude Code\]\([^)]*\)_?\s*$",
        re.IGNORECASE,
    ),
    re.compile(
        r"\n*(?:^|\n)_?(?:\N{ROBOT FACE}\s*)?Generated (?:by|with) \[Claude Code\]\([^)]*\)_?\s*$",
        re.IGNORECASE,
    ),
    # A bare session link on its own line. Harnesses append this beside the
    # footer or instead of it, and it names the tool as plainly as the footer
    # does. Only a whole-line match counts, so a body that cites a session in
    # a sentence keeps its prose.
    re.compile(
        r"\n?^\s*<?https?://claude\.ai/code/session_\S*>?\s*$",
        re.IGNORECASE | re.MULTILINE,
    ),
    # Trailer lines, anywhere in the body.
    re.compile(r"\n?^Co-Authored-By:\s*Claude\b.*$", re.IGNORECASE | re.MULTILINE),
    re.compile(r"\n?^Claude-Session:\s*\S+.*$", re.IGNORECASE | re.MULTILINE),
    re.compile(r"\n?^\s*\N{ROBOT FACE} Generated with .*$", re.MULTILINE),
]


def owned_repos():
    """Repos this workflow covers, read from whichever pass ledger has seen them."""
    names = set()
    for ledger in ("comment-pass", "doc-pass", "writing-pass"):
        d = STATE / ledger
        if not d.is_dir():
            continue
        for f in d.glob("*.json"):
            owner, _, repo = f.stem.partition("__")
            if owner and repo:
                names.add(f"{owner}/{repo}")
    return sorted(names)


def current_repo():
    """`owner/repo` for the checkout this is run from, read off the origin remote.

    Not `gh repo view`: that answers over GraphQL, which a cloud session's egress
    policy may refuse while leaving REST open. The remote URL is already on disk
    and cannot be refused.
    """
    r = subprocess.run(
        ["git", "remote", "get-url", "origin"], capture_output=True, text=True,
    )
    url = (r.stdout or "").strip().removesuffix(".git")
    for sep in ("github.com/", "github.com:"):
        if sep in url:
            return url.split(sep, 1)[1] or None
    return None


def gh_api(path, method=None, payload=None):
    """One GitHub REST call through gh, returning the decoded body.

    Every call here is REST rather than a `gh pr` subcommand. Those go out over
    GraphQL, and a cloud session that serves REST happily can answer GraphQL
    with a 403, which surfaces here as every repo being unreachable on a box
    where each one is readable.
    """
    args = ["gh", "api", path]
    if method:
        args += ["-X", method]
    if payload is not None:
        args += ["--input", "-"]
    r = subprocess.run(
        args, capture_output=True, text=True,
        input=json.dumps(payload) if payload is not None else None,
    )
    if r.returncode != 0:
        raise RuntimeError(r.stderr.strip() or "gh api failed")
    return json.loads(r.stdout or "[]")


def clean(text):
    """Return the body with every attribution artifact removed, or None if unchanged.

    Most of the footer patterns anchor to the end of the body, so removing one
    artifact can expose another that was not last when it was tried: a harness
    appending both a footer and a bare session link leaves the footer sitting
    behind the link, out of reach of a single pass. Sweeping until the text
    stops changing is what makes the result answer for itself, so `strip`
    output always passes `check`.
    """
    original = text or ""
    out = original
    for _ in range(len(PATTERNS) + 1):
        before = out
        for pat in PATTERNS:
            out = pat.sub("", out)
        if out == before:
            break
    out = out.rstrip() + ("\n" if text and text.endswith("\n") else "")
    return None if out == original else out


def sweep(repo, limit, write):
    """Report, and optionally repair, attribution in a repo's recent pull requests.

    Returns (found, repaired, reached). A repo that could not be listed reports
    reached=False rather than folding into a zero count: "nothing to fix" and
    "never looked" are the same two numbers, and only one of them is clean.
    """
    try:
        prs = gh_api(f"repos/{repo}/pulls?state=all&per_page={max(1, min(limit, 100))}")
    except RuntimeError as e:
        print(f"{repo}: unreachable ({e})", file=sys.stderr)
        return 0, 0, False

    found = repaired = 0
    for pr in prs:
        fixed = clean(pr.get("body"))
        if fixed is None:
            continue
        found += 1
        if not write:
            print(f"{repo}#{pr['number']}: attribution in body")
            continue
        try:
            gh_api(f"repos/{repo}/pulls/{pr['number']}", method="PATCH", payload={"body": fixed})
        except RuntimeError as e:
            print(f"{repo}#{pr['number']}: could not edit ({e})", file=sys.stderr)
            continue
        repaired += 1
        print(f"{repo}#{pr['number']}: stripped")
    return found, repaired, True


def main():
    ap = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    ap.add_argument("mode", choices=["check", "strip"],
                    help="check reports what it finds; strip rewrites the bodies")
    ap.add_argument("repos", nargs="*", metavar="OWNER/REPO",
                    help="defaults to the current repo, or every repo the ledgers know")
    ap.add_argument("--limit", type=int, default=20,
                    help="pull requests to examine per repo (default 20)")
    ap.add_argument("--all", action="store_true",
                    help="sweep every repo the ledgers know rather than the current one")
    args = ap.parse_args()

    repos = args.repos or (owned_repos() if args.all else [r for r in [current_repo()] if r])
    if not repos:
        print("no repo to sweep: run inside a repo, name one, or pass --all", file=sys.stderr)
        return 2

    total_found = total_repaired = unreachable = 0
    for repo in repos:
        f, r, reached = sweep(repo, args.limit, args.mode == "strip")
        total_found += f
        total_repaired += r
        unreachable += not reached

    missed = f" {unreachable} of {len(repos)} repo(s) unreachable." if unreachable else ""
    if args.mode == "strip":
        print(f"Stripped attribution from {total_repaired} of {total_found} affected pull request(s).{missed}")
    else:
        print(f"{total_found} pull request(s) carry attribution.{missed}")

    # A run that reached nothing has checked nothing, so it fails rather than
    # reporting the clean-looking zero it would otherwise end on.
    if unreachable == len(repos):
        return 1
    return 1 if args.mode == "check" and total_found else 0


if __name__ == "__main__":
    sys.exit(main())
