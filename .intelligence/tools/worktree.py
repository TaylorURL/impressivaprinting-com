#!/usr/bin/env python3
"""One worktree per agent, cut from develop, so two of them never share a checkout.

A repo has one primary checkout and any number of linked worktrees hanging off
the same object store. Agents that all work in the primary checkout share a
single HEAD and a single index: the second one to switch branches takes the
first one's uncommitted work with it, and neither can see that it happened.

A worktree costs a directory and removes the whole class of problem, because
each agent gets a working tree of its own. So `new` is the way work starts, and
`guard` is what stops it starting any other way: a PreToolUse hook that refuses
an edit in the primary checkout of a repo that has a develop branch to cut from.

Nothing closes a tree at the far end. A session runs from the home directory and
opens trees in several repos at once, and the landing that finishes one of them
deploys and cleans up nothing, so there is no moment at which the work being
finished and the tree being closable are both true. Opening is that moment
instead: every unit of work passes through `new`, and nothing else does, so
`new` sweeps what has already landed before it cuts the next one.

  new <slug>     sweep what has landed, then cut a worktree from origin/develop
  list           every worktree of this repo, and which is primary
  done [slug]    remove a worktree once its branch has landed
  sweep          remove every landed tree, and name every tree holding work
  guard          PreToolUse(Write|Edit): keep edits out of the primary checkout

Set INTELLIGENCE_ALLOW_PRIMARY_WRITES=1 for the rare edit that belongs in the primary
checkout and nowhere else. It is an override, not a workflow.
"""
from __future__ import annotations

import json
import os
import re
import shutil
import subprocess
import sys
from pathlib import Path

# Only the repos the workflow applies to. A cloned dependency has no develop
# branch to cut from and no reason to answer to this.
OWNED = ("bradley-t-t/", "TaylorURL/")

# Worktrees live outside the project directories on purpose: a sibling of the
# checkout looks like a second clone to anything scanning for drift.
ROOT = Path.home() / "Development" / "worktrees"

# What a directory under ROOT may still hold once its worktree is gone. Removing
# a tree deletes what git tracked and leaves what it was ignoring, so a landed
# tree can leave behind a directory holding nothing but build output. Everything
# named here is regenerated by a command; anything else keeps the directory
# alive, because a name nobody listed is the one case where it might matter.
REGENERABLE = {".DS_Store", ".next", ".nuxt", ".output", ".parcel-cache",
               ".svelte-kit", ".turbo", ".vercel", ".vite", "build", "dist",
               "node_modules", "out", "target"}

DESIGN_RUNS = Path.home() / ".intelligence" / "state" / "design-runs"


def open_design_run(target):
    """The id of a design run still open on `target`, if there is one.

    The run's file ledger is a list of paths under its targets. Removing the tree
    takes those paths with it, and the ledger can never be rebuilt, so the run
    cannot close and every later session stops on its Stop hook.
    """
    target = str(Path(target).resolve())
    for state in sorted(DESIGN_RUNS.glob("2*.json")):
        try:
            run = json.loads(state.read_text())
        except (ValueError, OSError):
            continue
        if run.get("closed"):
            continue
        for t in run.get("targets") or []:
            resolved = str(Path(t).resolve())
            if resolved == target or resolved.startswith(target + "/"):
                return run.get("id") or state.stem
    return None


def git(*args, cwd=None):
    """Run git and return stripped stdout, or "" when the command failed."""
    done = subprocess.run(("git", *args), cwd=cwd, capture_output=True, text=True)
    return done.stdout.strip() if done.returncode == 0 else ""


def repo_of(path):
    """The working tree containing `path`, or None when it is outside one."""
    start = Path(path)
    if not start.is_dir():
        start = start.parent
    while not start.exists() and start != start.parent:
        start = start.parent
    top = git("rev-parse", "--show-toplevel", cwd=str(start))
    return Path(top) if top else None


def is_owned(repo):
    url = git("remote", "get-url", "origin", cwd=str(repo))
    return any(o in url for o in OWNED)


def is_primary(repo):
    """Whether this tree is the repo's original checkout rather than a worktree.

    A linked worktree's git dir sits under `.git/worktrees/<name>`; the primary
    one is the `.git` directory itself.
    """
    gitdir = git("rev-parse", "--absolute-git-dir", cwd=str(repo))
    return bool(gitdir) and Path(gitdir).parent.name != "worktrees"


def has_develop(repo):
    return bool(git("rev-parse", "--verify", "--quiet", "origin/develop", cwd=str(repo)))


def slugify(text):
    slug = re.sub(r"[^a-z0-9]+", "-", text.lower()).strip("-")
    return slug or "work"


def label(tree):
    return "%s/%s" % (tree.parent.name, tree.name)


def landed(tree, branch):
    """Whether GitHub says this branch reached a merged pull request.

    Work leaves a worktree by landing, so a merged pull request is what finished
    means. The reading has to come from GitHub rather than from the commits: a
    squash puts the content on develop under a commit sharing neither id nor
    patch with the branch it came from, which leaves a branch that landed and a
    branch that was abandoned looking identical to anything reading git alone.

    None where the question could not be reached. The sweep removes nothing on a
    None, because a lookup that failed has to be told apart from a branch that
    never landed.
    """
    if not branch or not shutil.which("gh"):
        return None
    # The configured URL rather than the effective one: `git remote get-url`
    # applies any insteadOf rewrite, and where a rewrite points somewhere else
    # the question is still whether GitHub is the one holding the branch.
    if "github.com" not in git("config", "--get", "remote.origin.url", cwd=str(tree)):
        return None
    try:
        done = subprocess.run(
            ("gh", "pr", "list", "--head", branch, "--state", "merged",
             "--json", "number", "--jq", "length"),
            cwd=str(tree), capture_output=True, text=True, timeout=30)
    except (OSError, subprocess.SubprocessError):
        return None
    count = done.stdout.strip()
    if done.returncode != 0 or not count.isdigit():
        return None
    return int(count) > 0


def verdict(tree):
    """What the sweep does with one tree, and why.

    Three answers: remove it, hold it because something in it would go too, or
    keep it because the work is still in flight. Holding is what every question
    that could not be settled resolves to -- a tree removed in error takes the
    only copy of its work with it, and a tree held in error costs a directory
    and says so again on the next sweep.

    Every reason a tree is held comes back, not the first one found. They are
    not ranked, and the one that stops the removal is rarely the one worth
    knowing: an open design run holds a tree whatever else is true of it, and
    saying only that hides the commits underneath it that nothing else has.

    A landed branch is not read for commits no remote has. Squashing is what
    puts the work on develop, so every commit on the branch is one no remote
    holds, and treating that as work at risk would hold every tree forever.
    """
    reasons = []
    if git("status", "--porcelain", cwd=str(tree)):
        reasons.append("uncommitted changes")
    run = open_design_run(tree)
    if run:
        reasons.append("design run %s is open on it" % run)

    merged = landed(tree, git("branch", "--show-current", cwd=str(tree)))
    if merged is None:
        reasons.append("GitHub could not say whether it landed")
    elif not merged:
        held = git("rev-list", "HEAD", "--not", "--remotes", cwd=str(tree))
        if held:
            reasons.append("%d commit(s) on no remote and no merged pull request"
                           % len(held.splitlines()))

    if reasons:
        return "hold", "; ".join(reasons)
    return ("remove", "landed") if merged else ("keep", "no merged pull request yet")


def shell_removable(path):
    """Whether a directory under ROOT is residue rather than a worktree.

    A removed worktree leaves its ignored files behind, and the directory that
    holds them reads on disk exactly like an open tree.
    """
    if not path.is_dir() or (path / ".git").exists():
        return False
    return all(child.name in REGENERABLE for child in path.iterdir())


def clear_shell(path):
    if not shell_removable(path):
        return False
    shutil.rmtree(path, ignore_errors=True)
    return not path.exists()


def clear_empty_repo(path):
    """Remove a repo's directory under ROOT once its last tree has gone.

    Nothing reads these and nothing recreates them but `new`. Left standing they
    make the root read as though work is open in every repository, which is the
    reading the sweep exists to make true rather than to fake.
    """
    path = Path(path)
    if path.parent != ROOT or not path.is_dir() or any(path.iterdir()):
        return False
    path.rmdir()
    return True


def remove_tree(base_repo, target):
    """Take one worktree out, with its branch and whatever it leaves behind.

    Returns the branch that went with it, or an error where git refused.
    """
    branch = git("branch", "--show-current", cwd=str(target))
    done = subprocess.run(("git", "worktree", "remove", str(target)),
                          cwd=str(base_repo), capture_output=True, text=True)
    if done.returncode != 0:
        return None, done.stderr.strip()
    if branch:
        git("branch", "-D", branch, cwd=str(base_repo))
    clear_shell(target)
    clear_empty_repo(Path(target).parent)
    return branch or "detached", None


def cmd_sweep(argv):
    """Close every tree that has landed, and name every tree that has not.

    It runs over the whole worktrees root rather than the repo it was called
    from. One session opens trees in several repos and ends in none of them, so
    a sweep reaching only the repo in front of it would leave the rest to
    accumulate exactly as before.

    A tree still in flight is passed over in silence. Only the ones holding
    something are named, because a sweep that reports every tree it looked at on
    every run is a sweep nobody reads.
    """
    dry = "--dry-run" in argv
    if not ROOT.is_dir():
        return 0
    removed, holds, pruned = [], [], set()
    trees = sorted(tree for repo in ROOT.iterdir() if repo.is_dir()
                   for tree in repo.iterdir() if tree.is_dir())
    for tree in trees:
        common = git("rev-parse", "--path-format=absolute", "--git-common-dir",
                     cwd=str(tree))
        if not common:
            if shell_removable(tree) and (dry or clear_shell(tree)):
                removed.append(label(tree))
            continue
        base_repo = Path(common).parent
        if base_repo not in pruned:
            git("fetch", "--quiet", "origin", "--prune", cwd=str(base_repo))
            pruned.add(base_repo)
        answer, why = verdict(tree)
        if answer == "remove" and dry:
            removed.append(label(tree))
        elif answer == "remove":
            branch, err = remove_tree(base_repo, tree)
            (holds.append((label(tree), err)) if err
             else removed.append(label(tree)))
        elif answer == "hold":
            holds.append((label(tree), why))

    if not dry:
        for repo in sorted(ROOT.iterdir()):
            clear_empty_repo(repo)

    if removed:
        print("swept %d landed worktree(s): %s"
              % (len(removed), ", ".join(removed)))
    for name, why in holds:
        print("  held %s: %s" % (name, why))
    return 0


def cmd_new(argv):
    if not argv:
        print("usage: worktree.py new <slug>", file=sys.stderr)
        return 2
    repo = repo_of(Path.cwd())
    if repo is None:
        print("not inside a git repository", file=sys.stderr)
        return 2
    cmd_sweep([])
    # Always cut from the primary checkout, so `new` works from inside another
    # worktree without nesting one inside it.
    common = git("rev-parse", "--path-format=absolute", "--git-common-dir", cwd=str(repo))
    base_repo = Path(common).parent if common else repo

    git("fetch", "--quiet", "origin", "--prune", cwd=str(base_repo))
    if not has_develop(base_repo):
        print("origin/develop does not exist; this repo does not use the branch model",
              file=sys.stderr)
        return 2

    slug = slugify(" ".join(argv))
    name = base_repo.name
    dest = ROOT / name / slug
    if dest.exists():
        print("worktree already exists: %s" % dest)
        print(dest)
        return 0

    branch = slug
    if git("rev-parse", "--verify", "--quiet", "refs/heads/" + branch, cwd=str(base_repo)):
        print("a local branch named %s already exists; pick another slug" % branch,
              file=sys.stderr)
        return 2

    dest.parent.mkdir(parents=True, exist_ok=True)
    done = subprocess.run(
        ("git", "worktree", "add", "-b", branch, str(dest), "origin/develop"),
        cwd=str(base_repo), capture_output=True, text=True,
    )
    if done.returncode != 0:
        print(done.stderr.strip(), file=sys.stderr)
        return 2
    print("%s cut from origin/develop at %s" % (branch, git("rev-parse", "--short", "origin/develop", cwd=str(base_repo))))
    print(dest)
    return 0


def cmd_list(argv):
    repo = repo_of(Path.cwd())
    if repo is None:
        print("not inside a git repository", file=sys.stderr)
        return 2
    out = git("worktree", "list", "--porcelain", cwd=str(repo))
    path = None
    for line in out.splitlines():
        if line.startswith("worktree "):
            path = line.split(" ", 1)[1]
        elif line.startswith("branch ") and path:
            branch = line.split(" ", 1)[1].replace("refs/heads/", "")
            tag = "primary" if is_primary(Path(path)) else "worktree"
            dirty = "dirty" if git("status", "--porcelain", cwd=path) else "clean"
            print("%-9s %-28s %-6s %s" % (tag, branch, dirty, path))
            path = None
    return 0


def cmd_done(argv):
    repo = repo_of(Path.cwd())
    if repo is None:
        print("not inside a git repository", file=sys.stderr)
        return 2
    common = git("rev-parse", "--path-format=absolute", "--git-common-dir", cwd=str(repo))
    base_repo = Path(common).parent if common else repo
    target = ROOT / base_repo.name / slugify(" ".join(argv)) if argv else repo
    if is_primary(target):
        print("that is the primary checkout, not a worktree", file=sys.stderr)
        return 2
    if git("status", "--porcelain", cwd=str(target)):
        print("%s has uncommitted changes; land them before removing it" % target,
              file=sys.stderr)
        return 2
    blocker = open_design_run(target)
    if blocker:
        print("design run %s is open on %s; close it before removing the tree, or its\n"
              "file ledger goes with the directory:\n"
              "  ~/.intelligence/checklists/design/bin/design-pass.py report\n"
              "  ~/.intelligence/checklists/design/bin/design-pass.py finish"
              % (blocker, target), file=sys.stderr)
        return 2
    branch, err = remove_tree(base_repo, target)
    if err:
        print(err, file=sys.stderr)
        return 2
    print("removed %s (%s)" % (target, branch))
    return 0


def cmd_guard(argv):
    try:
        payload = json.load(sys.stdin)
    except (ValueError, OSError):
        return 0
    if os.environ.get("INTELLIGENCE_ALLOW_PRIMARY_WRITES"):
        return 0
    tool_input = payload.get("tool_input") or {}
    path = tool_input.get("file_path") or tool_input.get("notebook_path")
    if not path:
        return 0
    # Nothing under ~/.intelligence is project work: the config tree is edited in
    # place and its own mirror has no develop branch to cut from.
    if str(Path(path).expanduser()).startswith(str(Path.home() / ".intelligence")):
        return 0

    repo = repo_of(path)
    if repo is None or not is_owned(repo) or not is_primary(repo):
        return 0
    if not has_develop(repo):
        return 0

    slug = slugify(Path(path).stem)
    print(
        "BLOCKED: %s is the primary checkout of %s.\n"
        "\n"
        "Agents work in a worktree of their own, cut from develop. Two of them in\n"
        "one checkout share a HEAD and an index, so the second to switch branches\n"
        "takes the first one's uncommitted work with it and neither can tell.\n"
        "\n"
        "Open one and work there:\n"
        "  ~/.intelligence/tools/worktree.py new %s\n"
        "\n"
        "Then cd into the path it prints. `worktree.py list` shows what is already\n"
        "open; `worktree.py done <slug>` removes one after its branch has landed.\n"
        % (repo, repo.name, slug),
        file=sys.stderr,
    )
    return 2


COMMANDS = {"new": cmd_new, "list": cmd_list, "done": cmd_done,
            "sweep": cmd_sweep, "guard": cmd_guard}


def main():
    if len(sys.argv) < 2 or sys.argv[1] not in COMMANDS:
        print(__doc__.strip(), file=sys.stderr)
        return 2
    return COMMANDS[sys.argv[1]](sys.argv[2:])


if __name__ == "__main__":
    raise SystemExit(main())
